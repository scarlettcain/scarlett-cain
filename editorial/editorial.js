function createSlideshow(imgId, images) {
    let current = 0;
    const img = document.getElementById(imgId);

    img.src = images[current];

    return {
        next() {
            current = (current + 1) % images.length;
            img.src = images[current];
        },

        prev() {
            current = (current - 1 + images.length) % images.length;
            img.src = images[current];
        }
    };
}

